using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using Microsoft.Extensions.Logging;

namespace RadicalTrainingPlatform.Core;

/// <summary>One file a bundle declares, with the hash it must have.</summary>
public sealed record BundleFile(string Path, string Sha256, long Bytes);

/// <summary>A lesson the bundle ships, named by the manifest rather than discovered.</summary>
public sealed record BundleLesson(string LessonId, string Path, string Sha256);

/// <summary>A question bank the bundle ships.</summary>
public sealed record BundleBank(string Bank, string Path, string Sha256);

/// <summary>One exam the bundle ships: its manifest, lessons and banks.</summary>
public sealed record BundleExam(
    string ExamId,
    string ManifestPath,
    IReadOnlyList<BundleLesson> Lessons,
    IReadOnlyList<BundleBank> Banks);

/// <summary>
/// The content manifest a bundle ships. Generated by
/// scripts/generate-bundle-manifest.py before the bundle is packed, so what the
/// bundle claims to carry and what it carries come out of the same pass.
/// Paths are relative to the bundle root (the directory holding the manifest).
/// </summary>
public sealed record ContentBundleManifest(
    int BundleVersion,
    string GeneratedBy,
    string ReleaseState,
    string ReleaseNote,
    string Disclaimer,
    string ContentRoot,
    string? ErrataPath,
    IReadOnlyDictionary<string, BundleExam> Exams,
    IReadOnlyList<BundleBank> LegacyBanks,
    IReadOnlyList<BundleFile> Files);

/// <summary>
/// Raised when the app cannot find the content it was built to ship. The point
/// of this exception is that the alternative used to be silence: no content
/// directory meant an empty exam list and no error, which reads to a learner
/// exactly like "this app has nothing in it".
/// </summary>
public sealed class ContentBundleUnavailableException : Exception
{
    public IReadOnlyList<string> SearchedLocations { get; }

    public ContentBundleUnavailableException(string message, IReadOnlyList<string> searched)
        : base(message)
    {
        SearchedLocations = searched;
    }
}

/// <summary>
/// The content a bundle ships, as declared by its manifest.
/// </summary>
public interface IContentBundle
{
    /// <summary>True when a readable manifest was found and its content root exists.</summary>
    bool IsAvailable { get; }

    /// <summary>Directory holding the manifest; bundle-relative paths resolve from here.</summary>
    string? BundleRoot { get; }

    /// <summary>Absolute path to the content root named by the manifest.</summary>
    string? ContentRoot { get; }

    /// <summary>Absolute path to the errata file named by the manifest, if it names one.</summary>
    string? ErrataPath { get; }

    /// <summary>The parsed manifest, or null when none was found.</summary>
    ContentBundleManifest? Manifest { get; }

    /// <summary>Every location consulted, in order. Reported in the error.</summary>
    IReadOnlyList<string> SearchedLocations { get; }

    /// <summary>Why the bundle is unavailable, or null when it is available.</summary>
    string? UnavailableReason { get; }

    /// <summary>Resolve a bundle-relative path (POSIX separators) to an absolute path.</summary>
    string Resolve(string relativePath);

    /// <summary>
    /// Check every declared file exists and hashes to what the manifest says.
    /// Returns one human-readable line per problem; empty means the bundle is
    /// exactly what it claims to be.
    /// </summary>
    IReadOnlyList<string> Verify();

    /// <summary>
    /// Throw <see cref="ContentBundleUnavailableException"/> unless a bundle is
    /// present and its content root exists. Call this at startup so a missing
    /// bundle is a loud error instead of an empty screen.
    /// </summary>
    void EnsureAvailable();
}

/// <summary>
/// Finds and parses the content manifest.
///
/// It deliberately does NOT walk parent directories the way
/// <see cref="MarkdownExamRepository"/> does. That walk is a development
/// convenience that hides a packaging defect: run from a checkout and content
/// is found by accident, install the bundle and the same code finds nothing and
/// starts anyway. A manifest is either at a place a bundle puts it or it is not,
/// and "not" is an error the user gets to see.
/// </summary>
public sealed class ContentBundle : IContentBundle
{
    public const string ManifestFileName = "content-manifest.json";

    /// <summary>Set to a bundle root to skip location search entirely.</summary>
    public const string BundleRootEnvironmentVariable = "RADICALTRAININGPLATFORM_BUNDLE";

    private readonly IFileProvider _files;
    private readonly ILogger<ContentBundle>? _logger;
    private readonly string? _overrideRoot;
    private readonly Lazy<Resolved> _resolved;

    public ContentBundle(IFileProvider files, ILogger<ContentBundle>? logger = null,
                         string? bundleRoot = null)
    {
        _files = files;
        _logger = logger;
        _overrideRoot = bundleRoot;
        _resolved = new Lazy<Resolved>(Resolve1);
    }

    private sealed record Resolved(
        string? BundleRoot,
        ContentBundleManifest? Manifest,
        IReadOnlyList<string> Searched,
        string? Reason);

    public bool IsAvailable => _resolved.Value.Manifest != null
                               && _resolved.Value.BundleRoot != null
                               && _files.Exists(ContentRoot!);

    public string? BundleRoot => _resolved.Value.BundleRoot;

    public string? ContentRoot =>
        _resolved.Value is { BundleRoot: not null, Manifest: not null }
            ? _files.CombinePath(_resolved.Value.BundleRoot, _resolved.Value.Manifest.ContentRoot)
            : null;

    public string? ErrataPath =>
        _resolved.Value is { BundleRoot: not null, Manifest.ErrataPath: not null }
            ? _files.CombinePath(_resolved.Value.BundleRoot, _resolved.Value.Manifest.ErrataPath)
            : null;

    public ContentBundleManifest? Manifest => _resolved.Value.Manifest;

    public IReadOnlyList<string> SearchedLocations => _resolved.Value.Searched;

    public string? UnavailableReason => _resolved.Value.Reason;

    public string Resolve(string relativePath)
    {
        var root = BundleRoot ?? throw new ContentBundleUnavailableException(
            UnavailableReason ?? "no content bundle is available", SearchedLocations);
        return _files.CombinePath(root, relativePath.Replace('/', Path.DirectorySeparatorChar));
    }

    public IReadOnlyList<string> Verify()
    {
        var problems = new List<string>();
        var manifest = Manifest;
        if (manifest == null || BundleRoot == null)
        {
            problems.Add(UnavailableReason ?? "no content bundle is available");
            return problems;
        }

        foreach (var file in manifest.Files)
        {
            var absolute = Resolve(file.Path);
            if (!_files.Exists(absolute))
            {
                problems.Add($"missing: {file.Path}");
                continue;
            }

            string actual;
            try
            {
                actual = Hash(_files.ReadAllText(absolute));
            }
            catch (Exception ex)
            {
                problems.Add($"unreadable: {file.Path} ({ex.Message})");
                continue;
            }

            if (!string.Equals(actual, file.Sha256, StringComparison.OrdinalIgnoreCase))
                problems.Add($"hash mismatch: {file.Path} (manifest {file.Sha256[..12]}, actual {actual[..12]})");
        }
        return problems;
    }

    public void EnsureAvailable()
    {
        if (Manifest == null || BundleRoot == null)
        {
            // A manifest that was found but could not be used says so — "not
            // found" would send someone hunting for a file that is right there.
            throw new ContentBundleUnavailableException(
                UnavailableReason
                ?? $"No content bundle found. {ManifestFileName} was not present in any of the " +
                   $"locations searched: {string.Join(", ", SearchedLocations)}. " +
                   $"The app cannot run without its content; set {BundleRootEnvironmentVariable} " +
                   $"to the bundle root if the content lives somewhere else.",
                SearchedLocations);
        }

        var contentRoot = ContentRoot!;
        if (!_files.Exists(contentRoot))
        {
            throw new ContentBundleUnavailableException(
                $"The content bundle at {BundleRoot} declares content root " +
                $"'{Manifest!.ContentRoot}', but {contentRoot} does not exist. " +
                $"The bundle is incomplete.",
                SearchedLocations);
        }
    }

    private Resolved Resolve1()
    {
        var searched = new List<string>();
        foreach (var root in CandidateRoots())
        {
            if (string.IsNullOrWhiteSpace(root)) continue;
            var candidate = _files.CombinePath(root, ManifestFileName);
            if (!searched.Contains(candidate, StringComparer.OrdinalIgnoreCase))
                searched.Add(candidate);

            if (!_files.Exists(candidate)) continue;

            var (manifest, reason) = TryParse(candidate);
            if (manifest == null)
                return new Resolved(null, null, searched, reason);

            _logger?.LogInformation("Content bundle: {Manifest} ({State})",
                                    candidate, manifest.ReleaseState);
            return new Resolved(root, manifest, searched, null);
        }
        return new Resolved(null, null, searched, null);
    }

    /// <summary>
    /// Where a bundle puts its manifest. An installed bundle is found by its
    /// layout, a checkout by where it was launched, and a build tree by walking
    /// up from the binary — the last one is the same climb the repository used
    /// to do, and it is safe here for a reason it was not before: the walk looks
    /// for the manifest, and the manifest decides the content. When nothing is
    /// found the app fails loudly rather than falling back to whatever happened
    /// to be lying around, so the walk can no longer stand in for content that
    /// was not shipped.
    /// </summary>
    private IEnumerable<string> CandidateRoots()
    {
        if (!string.IsNullOrWhiteSpace(_overrideRoot))
        {
            yield return _overrideRoot!;
            yield break;
        }

        var fromEnv = Environment.GetEnvironmentVariable(BundleRootEnvironmentVariable);
        if (!string.IsNullOrWhiteSpace(fromEnv)) yield return fromEnv!;

        var baseDir = _files.GetExecutingAssemblyDirectory();
        yield return baseDir;
        // Linux AppImage / Flatpak: <root>/usr/bin/app -> <root>/usr/share/<app>/
        yield return _files.CombinePath(baseDir, "..", "share", "radicaltrainingplatform");
        // macOS: <App>.app/Contents/MacOS/app -> <App>.app/Contents/Resources/
        yield return _files.CombinePath(baseDir, "..", "Resources");
        yield return _files.GetCurrentDirectory();

        // Dev/build tree: bin/Release/net10.0 -> ... -> the checkout root.
        var current = baseDir;
        for (var depth = 0; depth < 6 && !string.IsNullOrEmpty(current); depth++)
        {
            var parent = _files.GetParentDirectory(current);
            if (string.IsNullOrEmpty(parent)) break;
            yield return parent;
            current = parent;
        }
    }

    private (ContentBundleManifest? Manifest, string? Reason) TryParse(string path)
    {
        string text;
        try
        {
            text = _files.ReadAllText(path);
        }
        catch (Exception ex)
        {
            _logger?.LogWarning(ex, "Could not read content manifest {Path}", path);
            return (null, $"the content manifest at {path} could not be read: {ex.Message}");
        }

        try
        {
            var options = new JsonSerializerOptions
            {
                PropertyNameCaseInsensitive = true,
                ReadCommentHandling = JsonCommentHandling.Skip,
                AllowTrailingCommas = true,
            };
            var dto = JsonSerializer.Deserialize<ManifestDto>(text, options);
            if (dto == null)
                return (null, $"the content manifest at {path} is empty");

            if (string.IsNullOrWhiteSpace(dto.ContentRoot))
                return (null, $"the content manifest at {path} declares no contentRoot");

            var exams = new Dictionary<string, BundleExam>(StringComparer.OrdinalIgnoreCase);
            foreach (var (examId, exam) in dto.Exams ?? new())
            {
                exams[examId] = new BundleExam(
                    examId,
                    exam.Manifest?.Path ?? "",
                    (exam.Lessons ?? new()).Select(l => new BundleLesson(l.LessonId ?? "", l.Path ?? "", l.Sha256 ?? "")).ToList(),
                    (exam.Banks ?? new()).Select(b => new BundleBank(b.Bank ?? "", b.Path ?? "", b.Sha256 ?? "")).ToList());
            }

            var manifest = new ContentBundleManifest(
                dto.BundleVersion,
                dto.GeneratedBy ?? "",
                dto.ReleaseState ?? "",
                dto.ReleaseNote ?? "",
                dto.Disclaimer ?? "",
                dto.ContentRoot!,
                dto.Errata?.Path,
                exams,
                (dto.LegacyBanks ?? new()).Select(b => new BundleBank(b.Bank ?? "", b.Path ?? "", b.Sha256 ?? "")).ToList(),
                (dto.Files ?? new()).Select(f => new BundleFile(f.Path ?? "", f.Sha256 ?? "", f.Bytes)).ToList());

            return (manifest, null);
        }
        catch (JsonException ex)
        {
            _logger?.LogWarning(ex, "Malformed content manifest {Path}", path);
            return (null, $"the content manifest at {path} is malformed JSON: {ex.Message}");
        }
    }

    /// <summary>
    /// SHA-256 of a file's text. Content files are UTF-8 without a BOM (checked
    /// for the shipped tree), so hashing the re-encoded text matches hashing the
    /// bytes; a file that gains a BOM will fail verification, which is the
    /// honest outcome — it is not the file the manifest describes.
    /// </summary>
    private static string Hash(string text) =>
        Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(text))).ToLowerInvariant();

    // Shapes of the generated manifest. Kept private: callers get the records above.
    private sealed class ManifestDto
    {
        public int BundleVersion { get; set; }
        public string? GeneratedBy { get; set; }
        public string? ReleaseState { get; set; }
        public string? ReleaseNote { get; set; }
        public string? Disclaimer { get; set; }
        public string? ContentRoot { get; set; }
        public FileDto? Errata { get; set; }
        public Dictionary<string, ExamDto>? Exams { get; set; }
        public List<BankDto>? LegacyBanks { get; set; }
        public List<FileDto>? Files { get; set; }
    }

    private sealed class ExamDto
    {
        public FileDto? Manifest { get; set; }
        public List<LessonDto>? Lessons { get; set; }
        public List<BankDto>? Banks { get; set; }
    }

    private sealed class LessonDto : FileDto
    {
        public string? LessonId { get; set; }
    }

    private sealed class BankDto : FileDto
    {
        public string? Bank { get; set; }
    }

    private class FileDto
    {
        public string? Path { get; set; }
        public string? Sha256 { get; set; }
        public long Bytes { get; set; }
    }
}
